/** Opens our sailings page with the destination already chosen on the live search form. */
export function sailingSearchHref(slug: string) {
  if (slug === "rail") return desk.tours;
  if (slug === "expedition") return "/sailings";
  const params = new URLSearchParams();
  if (slug === "river") params.set("destinationtype", "River");
  else {
    const id = cruiseDestinationId[slug];
    if (id) params.set("destinations", id);
  }
  const query = params.toString();
  return query ? `/sailings?${query}` : "/sailings";
}

/** Quoted sailings. Dates are MM/DD/YYYY. */
export function cruiseResultsHref(input: {
  destinationId?: string;
  destinationType?: string;
  start?: string;
  end?: string;
  minNights?: string;
  maxNights?: string;
}) {
  const url = new URL("https://book.myagentgenie.com/swift/cruise");
  url.searchParams.set("siid", "1178549");
  url.searchParams.set("lang", "1");
  if (input.destinationId) url.searchParams.set("destinations", input.destinationId);
  if (input.destinationType) url.searchParams.set("destinationtype", input.destinationType);
  if (input.start) url.searchParams.set("startdate", input.start);
  if (input.end) url.searchParams.set("enddate", input.end);
  if (input.minNights) url.searchParams.set("minduration", input.minNights);
  if (input.maxNights) url.searchParams.set("maxduration", input.maxNights);
  return url.toString();
}
